// pdf.js - Print-ready Document Checklist generator with strict HTML escaping
import { escapeHtml } from './security.js';

export function printChecklist({ schemes = [], documents = {}, lang = 'en' }) {
  const docCountMap = {};
  schemes.forEach(s => {
    if (Array.isArray(s.documents)) {
      s.documents.forEach(docId => {
        if (!docCountMap[docId]) docCountMap[docId] = [];
        docCountMap[docId].push(s.name?.[lang] || s.name?.en || s.id);
      });
    }
  });

  const docIds = Object.keys(docCountMap);
  const docListHtml = docIds.map(id => {
    const docMeta = documents[id] || {};
    const title = escapeHtml(docMeta[lang] || docMeta.en || id);
    const howTo = escapeHtml(docMeta.howToGet?.[lang] || docMeta.howToGet?.en || '');
    const schemeList = escapeHtml(docCountMap[id].join(', '));

    return `
      <div style="border-bottom: 1px solid #e5e7eb; padding: 12px 0;">
        <div style="display: flex; align-items: flex-start; gap: 10px;">
          <div style="width: 20px; height: 20px; border: 2px solid #374151; border-radius: 4px; margin-top: 2px; flex-shrink: 0;"></div>
          <div style="flex-grow: 1;">
            <div style="font-weight: 600; font-size: 16px; color: #111827;">${title}</div>
            ${howTo ? `<div style="font-size: 13px; color: #4b5563; margin-top: 2px;"><strong>How to obtain:</strong> ${howTo}</div>` : ''}
            <div style="font-size: 12px; color: #6b7280; margin-top: 4px;"><strong>Needed for:</strong> ${schemeList}</div>
          </div>
        </div>
      </div>
    `;
  }).join('');

  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    alert('Please allow popups to print your checklist.');
    return;
  }

  // Prevent window.opener vulnerability
  printWindow.opener = null;

  const safeLang = escapeHtml(lang);
  const safeDocCount = Number(docIds.length);
  const safeSchemeCount = Number(schemes.length);

  const printHtml = `<!DOCTYPE html><html lang="${safeLang}"><head><meta charset="UTF-8"><title>SchemeSetu - Document Checklist</title><style>body{font-family:system-ui,-apple-system,sans-serif;margin:40px auto;max-width:760px;color:#1f2937;line-height:1.5}.header{border-bottom:3px solid #FF9933;padding-bottom:16px;margin-bottom:24px}.logo{font-size:24px;font-weight:800;color:#FF9933}.tagline{font-size:14px;color:#6b7280}.summary-box{background:#f3f4f6;padding:12px 16px;border-radius:8px;margin-bottom:24px;font-size:14px}@media print{body{margin:15mm}.no-print{display:none}}</style></head><body><div class="header"><div class="logo">SchemeSetu</div><div class="tagline">Government Welfare Scheme Document Checklist</div></div><div class="summary-box"><strong>${safeDocCount} Document(s) Required</strong> to apply for <strong>${safeSchemeCount} Scheme(s)</strong>.<br/><em>Note: Carry both original and self-attested photocopies to the registration center.</em></div><div>${docListHtml}</div><div style="margin-top:40px;border-top:1px solid #e5e7eb;padding-top:12px;font-size:11px;color:#9ca3af;text-align:center;">Generated by SchemeSetu (schemesetu.org) • Verified against official government portals.</div><script>window.onload=function(){window.print();}</script></body></html>`;

  printWindow.document.open();
  printWindow.document.write(printHtml);
  printWindow.document.close();
}
